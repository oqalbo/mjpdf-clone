"""The fixture manifest.

Tests assert fixture facts literally: page counts, hit counts, outline
destinations, link targets, highlight colours. Those numbers have to come from
somewhere a test author can read, and they must be regenerated whenever a
fixture changes, or a test asserts a number the file no longer has.

Every generator registers what it produced. The manifest is written as JSON for
machines and as a Markdown table for people, both into the output directory.
"""

import hashlib
import json
import os

_ENTRIES = {}


class FixtureRecord:
    def __init__(self, name, path, description):
        self.name = name
        self.path = path
        self.description = description
        self.facts = {}
        self.tags = []

    def tag(self, *names):
        self.tags.extend(names)
        return self


def register(name, path, description, **facts) -> FixtureRecord:
    rec = FixtureRecord(name, path, description)
    rec.facts.update(facts)
    _ENTRIES[name] = rec
    return rec


def all_records():
    return dict(sorted(_ENTRIES.items()))


def reset():
    _ENTRIES.clear()


def _describe_file(path):
    if not os.path.exists(path):
        return {"exists": False}
    data = open(path, "rb").read()
    return {
        "exists": True,
        "bytes": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
    }


def write(out_dir):
    records = all_records()
    payload = {}
    for name, rec in records.items():
        rel = os.path.relpath(rec.path, out_dir) if rec.path else None
        payload[name] = {
            "path": rel,
            "description": rec.description,
            "tags": sorted(set(rec.tags)),
            "facts": rec.facts,
            "file": _describe_file(rec.path) if rec.path else {"exists": False},
        }
    with open(os.path.join(out_dir, "MANIFEST.json"), "w") as fh:
        json.dump(payload, fh, indent=2, sort_keys=True, ensure_ascii=False)
        fh.write("\n")

    lines = [
        "# Fixture manifest",
        "",
        "Generated by `python3 generate.py`. Do not edit by hand.",
        "",
        "Every number here is asserted literally by at least one test. If a "
        "fixture is regenerated with different content, the tests that read "
        "these values must be updated in the same commit.",
        "",
        f"{len(records)} fixtures.",
        "",
        "| Fixture | Bytes | Description | Facts |",
        "| --- | --- | --- | --- |",
    ]
    for name, rec in records.items():
        info = _describe_file(rec.path) if rec.path else {"exists": False}
        size = f"{info.get('bytes', 0):,}" if info.get("exists") else "missing"
        facts = "<br>".join(f"`{k}` = {_fmt(v)}" for k, v in rec.facts.items())
        lines.append(f"| `{name}` | {size} | {rec.description} | {facts or '-'} |")
    lines.append("")
    with open(os.path.join(out_dir, "MANIFEST.md"), "w") as fh:
        fh.write("\n".join(lines))
    return len(records)


def _fmt(v):
    if isinstance(v, (list, tuple)):
        if len(v) > 8:
            return f"{len(v)} entries"
        return ", ".join(str(x) for x in v)
    if isinstance(v, dict):
        return f"{len(v)} keys"
    return str(v)
